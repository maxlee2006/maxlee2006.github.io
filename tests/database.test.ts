test('migration and import are repeatable; public roles cannot write or read drafts', async () => {
  const db = new PGlite()
  try {
    await db.exec('create role anon; create role authenticated;')
    // A legacy table, permissive policy, and column grant must not defeat CMS permissions.
    await db.exec(`create table public."Modals" (id bigint generated by default as identity primary key, title text, private_notes text);
      insert into public."Modals" (title,private_notes) values ('Legacy draft','Private');
      alter table public."Modals" enable row level security;
      create policy legacy_open on public."Modals" for all to public using (true) with check (true);
      grant all on public."Modals" to anon, authenticated;
      grant update(title), select(private_notes) on public."Modals" to anon, authenticated;`)
    await db.exec(migration)
    await db.exec(seedSql())
    await db.exec(migration)
    await db.exec(seedSql())
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Modals"')).rows[0].count, 13)
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Articles"')).rows[0].count, 1)
    for (const role of ['anon', 'authenticated']) {
      await db.exec(`set role ${role}`)
      for (const table of ['Articles', 'Modals']) {
        const result = await db.query(`select ${columns} from public."${table}"`)
        assert.equal(result.rows.length, table === 'Articles' ? 1 : 12)
        assert.equal((await db.query(`select slug from public."${table}" where published is not true`)).rows.length, 0)
        await assert.rejects(db.exec(`insert into public."${table}" (slug) values ('unauthorized')`), /permission denied/)
        await assert.rejects(db.exec(`update public."${table}" set title = 'tampered'`), /permission denied/)
        await assert.rejects(db.exec(`delete from public."${table}"`), /permission denied/)
        await assert.rejects(db.exec(`truncate public."${table}"`), /permission denied/)
      }
      await assert.rejects(db.exec('select private_notes from public."Modals"'), /permission denied/)
      await db.exec('reset role')
    }
    // Even a later permissive write grant cannot override restrictive RLS policies.
    await db.exec('grant insert, update, delete on public."Modals" to anon; set role anon;')
    assert.equal((await db.query('update public."Modals" set title = \'tampered\' returning slug')).rows.length, 0)
    assert.equal((await db.query('delete from public."Modals" returning slug')).rows.length, 0)
    await assert.rejects(db.exec('insert into public."Modals" (slug,title,page,category,published,content) values (\'test\',\'Test\',\'portfolio\',\'modeling\',true,\'{"thumbnail":"/test.png","body":[]}\')'), /row-level security|permission denied/)
  } finally { await db.close() }
})

test('incompatible existing schema rolls back without changing user data', async () => {
  const db = new PGlite()
  try {
    await db.exec('create role anon; create role authenticated; create table public."Articles" (title text, content text); insert into public."Articles" values (\'Keep\',\'original\');')
    await assert.rejects(db.exec(migration), /Incompatible/)
    await db.exec('rollback')
    assert.deepEqual((await db.query('select * from public."Articles"')).rows, [{ title: 'Keep', content: 'original' }])
  } finally { await db.close() }
})

test('live legacy required fields become optional without changing existing rows or matching content', async () => {
  const db = new PGlite()
  try {
    await db.exec(`create role anon; create role authenticated;
      create table public."Articles" (
        id bigint generated by default as identity primary key,
        slug text not null default '', title text not null default '',
        published boolean not null default false, body json not null,
        cover_image text not null default '', created_at timestamptz not null default now()
      );
      create table public."Modals" (
        id bigint generated by default as identity primary key,
        slug text not null default '', published boolean not null default false,
        body json not null, page_id bigint not null,
        display_order bigint not null default 0, created_at timestamptz not null default now()
      );
      insert into public."Articles" (slug,title,body,cover_image)
        values ('long-march','Owner draft','{"keep":"article"}','/owner.png');
      insert into public."Modals" (slug,body,page_id,display_order)
        values ('owner-draft','{"keep":"modal"}',42,7);`)
    const beforeArticle = (await db.query<Record<string, unknown>>('select * from public."Articles"')).rows[0]
    const beforeModal = (await db.query<Record<string, unknown>>('select * from public."Modals"')).rows[0]
    await db.exec(migration)
    await db.exec(seedSql())
    await db.exec(migration)
    await db.exec(seedSql())
    for (const [table, before] of [['Articles', beforeArticle], ['Modals', beforeModal]] as const) {
      const after = (await db.query<Record<string, unknown>>(`select * from public."${table}" where id = 1`)).rows[0]
      for (const [field, value] of Object.entries(before)) assert.deepEqual(after[field], value, `${table}.${field}`)
    }
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Articles"')).rows[0].count, 1)
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Modals"')).rows[0].count, 13)
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Modals" where body is null and page_id is null')).rows[0].count, 12)
    await db.exec(securityCheck)
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Articles" where slug=\'cms-security-probe\'')).rows[0].count, 0)
    assert.equal((await db.query<{ count: number }>('select count(*)::int as count from public."Modals" where slug=\'cms-security-probe\'')).rows[0].count, 0)
  } finally { await db.close() }
})
