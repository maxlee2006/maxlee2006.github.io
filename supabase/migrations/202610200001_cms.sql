-- Run as the database owner in Supabase SQL Editor, after reviewing existing columns.
-- Transactional and repeatable: never deletes rows, tables, or unrelated policies.
-- A migration changes the database's structure/rules, not the website files.
-- BEGIN starts a transaction; COMMIT at the end saves it. An error prevents
-- partial changes. This script is for an owner connection, never a visitor.
begin;

-- public is a PostgreSQL schema (a namespace), not a promise of public access.
-- Quotes preserve the capital letters in these existing table names.
-- id is the database's internal row identifier; the site uses slug for links.

create table if not exists public."Articles" (
  id bigint generated by default as identity primary key
);
create table if not exists public."Modals" (
  id bigint generated by default as identity primary key
);

-- DO runs a small PostgreSQL program. Loop over both tables to apply identical
-- rules. format(... %I ...) quotes table/column identifiers safely; $$ and other
-- dollar delimiters wrap SQL strings without escaping every single quote.
do $$
declare
  table_name text;
  column_name text;
  policy_name text;
  existing_type text;
begin
  foreach table_name in array array['Articles', 'Modals'] loop
    -- Columns are named fields. jsonb stores structured JSON; boolean stores
    -- true/false. Defaults fill omitted fields on new rows, not complete content.
    -- New entries start unpublished so an unfinished draft isn't exposed.
    execute format('alter table public.%I add column if not exists slug text', table_name);
    execute format('alter table public.%I add column if not exists title text', table_name);
    execute format('alter table public.%I add column if not exists page text', table_name);
    execute format('alter table public.%I add column if not exists category text', table_name);
    execute format('alter table public.%I add column if not exists sort_order integer not null default 0', table_name);
    execute format('alter table public.%I add column if not exists published boolean not null default false', table_name);
    execute format('alter table public.%I add column if not exists content jsonb not null default ''{"body":[]}''::jsonb', table_name);

    -- The live project's old CMS used required body/page_id columns without defaults.
    -- The new CMS writes content/page instead. Keep legacy values and columns, but
    -- allow them to be omitted by the seed and future Table Editor inserts.
    for column_name in
      select a.attname::text from pg_attribute a
      where a.attrelid = format('public.%I', table_name)::regclass
        and a.attnum > 0 and not a.attisdropped and a.attnotnull
        and (a.attname = 'body' or (table_name = 'Modals' and a.attname = 'page_id'))
    loop
      execute format('alter table public.%I alter column %I drop not null', table_name, column_name);
    end loop;

    -- Fail atomically on incompatible existing types; never coerce/delete existing data.
    for column_name, existing_type in
      select a.attname::text, format_type(a.atttypid, a.atttypmod)
      from pg_attribute a
      where a.attrelid = format('public.%I', table_name)::regclass and not a.attisdropped
        and a.attname in ('slug', 'title', 'page', 'category', 'sort_order', 'published', 'content')
    loop
      if (column_name in ('slug', 'title', 'page', 'category') and existing_type not in ('text', 'character varying'))
        or (column_name = 'sort_order' and existing_type <> 'integer')
        or (column_name = 'published' and existing_type <> 'boolean')
        or (column_name = 'content' and existing_type <> 'jsonb') then
        raise exception 'Incompatible %.% type: %. Review the schema before adapting this migration.', table_name, column_name, existing_type;
      end if;
    end loop;

    -- A unique index prevents duplicate slugs within a table. The same slug
    -- may exist once in Articles AND once in Modals; they are separate tables.
    execute format('create unique index if not exists %I on public.%I (slug)', table_name || '_cms_slug_key', table_name);
    execute format('alter table public.%I drop constraint if exists cms_published_content', table_name);
    -- A constraint is a database-enforced validity rule. Drafts may be incomplete;
    -- published rows need the basic CMS fields below. NOT VALID skips checking
    -- all old rows now, but still checks new/changed rows. Validate old rows after
    -- reviewing/importing them (see docs). The application checks body blocks and
    -- URL safety in more detail; this SQL check does not duplicate every Zod rule.
    execute format($check$
      alter table public.%I add constraint cms_published_content check (
        published is not true or (
          slug is not null and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
          and title is not null and length(title) > 0
          and sort_order is not null
          and ((page = 'portfolio' and category in ('modeling', 'animation', 'sketches'))
            or (page = 'design' and category = 'ue')
            or (page = 'professional-projects' and category in ('custom-engines', 'web-development')))
          and page is not null and category is not null
          and content is not null and jsonb_typeof(content) = 'object'
          and content ? 'body' and jsonb_typeof(content->'body') = 'array'
          and content ? 'thumbnail' and jsonb_typeof(content->'thumbnail') = 'string'
        )
      ) not valid
    $check$, table_name);

    -- Permissions answer two different questions:
    -- 1. GRANT/REVOKE: which operations and columns can this role use?
    -- 2. RLS (row-level security): which rows can it see/change?
    -- anon means visitors without a login; authenticated means signed-in API
    -- users. Both are read-only here. PUBLIC below means every database role,
    -- whereas public.%I above names the schema. FORCE also subjects ordinary
    -- table owners to RLS; database superusers/bypass roles remain privileged.
    execute format('alter table public.%I enable row level security', table_name);
    execute format('alter table public.%I force row level security', table_name);
    execute format('revoke all privileges on table public.%I from public, anon, authenticated', table_name);
    -- Table-level REVOKE does not remove legacy column-level grants.
    for column_name in
      select a.attname::text from pg_attribute a
      where a.attrelid = format('public.%I', table_name)::regclass and a.attnum > 0 and not a.attisdropped
    loop
      execute format('revoke all privileges (%I) on table public.%I from public, anon, authenticated', column_name, table_name);
    end loop;
    execute format('grant select (slug, title, page, category, sort_order, published, content) on public.%I to anon, authenticated', table_name);

    foreach policy_name in array array['cms_public_read', 'cms_published_only', 'cms_no_insert', 'cms_no_update', 'cms_no_delete'] loop
      execute format('drop policy if exists %I on public.%I', policy_name, table_name);
    end loop;
    execute format('create policy cms_public_read on public.%I for select to anon, authenticated using (published is true)', table_name);
    -- Permissive policies combine with OR (any can allow); restrictive policies
    -- combine with AND (every applicable restriction must pass). Keep a read
    -- policy that permits published rows AND a restriction that still hides
    -- drafts if an older permissive policy is present. False write restrictions
    -- add protection if someone later grants INSERT/UPDATE/DELETE by mistake.
    -- USING checks existing rows; WITH CHECK checks proposed new row values.
    execute format('create policy cms_published_only on public.%I as restrictive for select to anon, authenticated using (published is true)', table_name);
    execute format('create policy cms_no_insert on public.%I as restrictive for insert to anon, authenticated with check (false)', table_name);
    execute format('create policy cms_no_update on public.%I as restrictive for update to anon, authenticated using (false) with check (false)', table_name);
    execute format('create policy cms_no_delete on public.%I as restrictive for delete to anon, authenticated using (false)', table_name);
  end loop;
end $$;

-- Ask Supabase's REST API layer (PostgREST) to refresh its cached knowledge of
-- columns/grants after commit, so HTTP requests can use the updated structure.
notify pgrst, 'reload schema';
commit;
